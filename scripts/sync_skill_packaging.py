#!/usr/bin/env python3
"""Make every skill directory self-contained enough to distribute alone.

Each skill gets a copy of the repository LICENSE, a `license:` frontmatter key
and a generated README.md. A skill directory leaves this repository on its own
in two ways: the TUI copies it to ~/.claude/skills/, and the release workflow
zips each one separately. In both cases the LICENSE at the repository root does
not travel with it, and Apache-2.0 section 4(a) requires that it does.

The README is generated rather than written by hand. The skill index drifted to
31 of 42 because it was hand-maintained, and 42 hand-written READMEs would go
the same way faster.

Usage:
    python scripts/sync_skill_packaging.py           # write
    python scripts/sync_skill_packaging.py --check   # exit 1 if out of date

Requires PyYAML.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import skill_roots  # noqa: E402

REPO_ROOT = skill_roots.REPO_ROOT
ROOT_LICENSE = REPO_ROOT / "LICENSE"

LICENCE_ID = "Apache-2.0"
GENERATED_NOTE = (
    "<!-- Generated by scripts/sync_skill_packaging.py. "
    "Edit SKILL.md instead; this file is rebuilt from it. -->"
)


def frontmatter(skill_md: Path) -> dict:
    parts = skill_md.read_text(encoding="utf-8").split("---", 2)
    if len(parts) < 3:
        return {}
    meta = yaml.safe_load(parts[1])
    return meta if isinstance(meta, dict) else {}


def bundled_files(skill_dir: Path) -> list[str]:
    """Every file a reader would want listed, relative to the skill directory.

    Sorted by directory then name so the output is stable across filesystems;
    an unsorted iterdir would make the README churn between machines.
    """
    out: list[str] = []
    for sub in ("references", "resources", "scripts", "templates", "assets", "examples"):
        d = skill_dir / sub
        if d.is_dir():
            out.extend(f"{sub}/{p.name}" for p in sorted(d.iterdir()) if p.is_file())
    return out


def render_readme(skill_dir: Path) -> str:
    meta = frontmatter(skill_dir / "SKILL.md")
    name = str(meta.get("name", skill_dir.name))
    description = " ".join(str(meta.get("description", "")).split())
    version = str((meta.get("metadata") or {}).get("version", "")).strip()
    licence = str(meta.get("license", LICENCE_ID))

    lines = [GENERATED_NOTE, "", f"# {name}", ""]
    if description:
        lines += [description, ""]

    facts = [f"- **Entry point:** [SKILL.md](SKILL.md)"]
    if version:
        facts.append(f"- **Version:** {version}")
    facts.append(f"- **Licence:** {licence}, see [LICENSE](LICENSE)")
    lines += facts + [""]

    lines += [
        "## Install",
        "",
        "Copy this directory into either skills location, then start a new session:",
        "",
        "```bash",
        f"cp -r {name} ~/.claude/skills/       # personal, all projects",
        f"cp -r {name} .claude/skills/         # this project only",
        "```",
        "",
        "For Claude Desktop, zip the directory and upload it under",
        "Settings, Capabilities, Skills. Released builds attach a ready-made zip.",
        "",
    ]

    files = bundled_files(skill_dir)
    if files:
        lines += [
            "## Bundled files",
            "",
            "Loaded on demand, not up front. SKILL.md routes to them.",
            "",
        ]
        lines += [f"- `{f}`" for f in files]
        lines.append("")

    group = skill_roots.group_of(skill_dir)
    if group is None:
        lines += [
            "## Part of a larger set",
            "",
            "One of the skills in [claude-skills](https://github.com/markpitt/claude-skills).",
            "See the [full list](../README.md).",
            "",
        ]
    else:
        lines += [
            "## Part of a larger set",
            "",
            # "API skills" and ".NET skills" already end in the word; do not say it twice.
            f"One of the {group.title.removesuffix(' skills')} skills (`{group.id}`). See the [group's list](../../README.md),",
            "or every group in [claude-skills](https://github.com/markpitt/claude-skills).",
            "",
        ]
    return "\n".join(lines)


def _licence_problems(skill_dir: Path, licence_text: str) -> list[str]:
    problems = []
    target = skill_dir / "LICENSE"
    if not target.is_file():
        problems.append(f"{skill_dir.name}: missing LICENSE")
    elif target.read_text(encoding="utf-8") != licence_text:
        problems.append(f"{skill_dir.name}: LICENSE differs from the repository licence")
    meta = frontmatter(skill_dir / "SKILL.md")
    if meta.get("license") != LICENCE_ID:
        problems.append(f"{skill_dir.name}: frontmatter license is {meta.get('license')!r}")
    return problems


def check(skills_root: Path | list[Path], licence_text: str) -> list[str]:
    roots = skills_root if isinstance(skills_root, list) else [skills_root]
    problems: list[str] = []
    for skill_dir in skill_roots.skill_dirs(roots):
        if not (skill_dir / "SKILL.md").exists():
            continue
        problems.extend(_licence_problems(skill_dir, licence_text))
        readme = skill_dir / "README.md"
        expected = render_readme(skill_dir)
        if not readme.is_file():
            problems.append(f"{skill_dir.name}: missing README.md")
        elif readme.read_text(encoding="utf-8") != expected:
            problems.append(f"{skill_dir.name}: README.md is out of date")
    return problems


def add_licence_key(skill_md: Path) -> bool:
    """Insert `license:` after `description:`, preserving the rest verbatim."""
    text = skill_md.read_text(encoding="utf-8")
    if frontmatter(skill_md).get("license") == LICENCE_ID:
        return False
    head, fm, body = text.split("---", 2)
    lines = fm.strip("\n").splitlines()
    out, inserted = [], False
    for line in lines:
        if line.startswith("license:"):
            continue
        out.append(line)
        # after the description block, which may wrap onto indented lines
        if not inserted and line.startswith("description:"):
            out.append(f"license: {LICENCE_ID}")
            inserted = True
    if not inserted:
        out.append(f"license: {LICENCE_ID}")
    skill_md.write_text(f"{head}---\n" + "\n".join(out) + f"\n---{body}", encoding="utf-8")
    return True


def main(argv: list[str]) -> int:
    roots = skill_roots.skills_roots()
    missing = skill_roots.missing_roots(roots)
    if missing:
        for root in missing:
            print(f"FATAL: skills root does not exist: {root}", file=sys.stderr)
        return 2
    if not ROOT_LICENSE.is_file():
        print(f"FATAL: no LICENSE at {ROOT_LICENSE}", file=sys.stderr)
        return 2

    licence_text = ROOT_LICENSE.read_text(encoding="utf-8")
    skills = [p for p in skill_roots.skill_dirs(roots) if (p / "SKILL.md").exists()]
    if not skills:
        print(f"FATAL: no skills found under {', '.join(map(str, roots))}", file=sys.stderr)
        return 2

    if "--check" in argv:
        problems = check(roots, licence_text)
        if problems:
            print("skill packaging is out of date:", file=sys.stderr)
            for p in problems:
                print(f"  {p}", file=sys.stderr)
            print("       run 'mise run skill:sync' and commit the result.", file=sys.stderr)
            return 1
        print(f"skill packaging is current ({len(skills)} skills)")
        return 0

    written = 0
    for skill_dir in skills:
        (skill_dir / "LICENSE").write_text(licence_text, encoding="utf-8")
        add_licence_key(skill_dir / "SKILL.md")
        (skill_dir / "README.md").write_text(render_readme(skill_dir), encoding="utf-8")
        written += 1
    print(f"synced {written} skills: LICENSE, license frontmatter, README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
